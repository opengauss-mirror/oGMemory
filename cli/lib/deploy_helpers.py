"""Docker deployment helpers for ogmem onboard."""

from __future__ import annotations

import logging
import os
import shlex
import subprocess
from pathlib import Path

from cli.lib.config_loader import get_project_root
from cli.lib.local_runtime import private_write

logger = logging.getLogger(__name__)

# These services use the quickstart's OpenAI-compatible chat API. Embedding
# needs a separate adapter name because Volcengine uses a different protocol.
QUICKSTART_EMBEDDING_PROVIDERS = {
    "openai": "openai",
    "volcengine": "volcengine",
    "dashscope": "openai",
    "zhipu": "openai",
}

def generate_quickstart_env(
    llm_config: dict,
    embedding_config: dict,
    *,
    vector_config: dict | None = None,
    instance_name: str = "ogmem",
    opengauss_port: int = 15432,
    ogmem_http_port: int = 18090,
    ogmem_mcp_port: int = 18091,
    openclaw_ce_port: int = 18790,
    openclaw_mcp_port: int = 18791,
    output_path: Path,
) -> Path:
    """Generate the environment file consumed by deploy/user-quickstart."""

    llm_provider = llm_config.get("provider", "openai")
    embedding_provider = embedding_config.get("provider", "openai")
    for kind, provider in (("LLM", llm_provider), ("Embedding", embedding_provider)):
        if provider not in QUICKSTART_EMBEDDING_PROVIDERS:
            raise ValueError(
                f"Docker quickstart does not support {kind} provider {provider!r}; "
                "choose openai, volcengine, dashscope, or zhipu. "
                "Use local mode for mock providers."
            )

    vector_config = vector_config or {"type": "opengauss"}
    backend = vector_config.get("type", "opengauss")
    if backend not in {"opengauss", "milvus"}:
        raise ValueError(f"Unsupported Docker vector provider: {backend!r}")
    values = {
        "VECTOR_DB_TYPE": backend,
        "MILVUS_URI": vector_config.get("milvus_uri", os.environ.get("MILVUS_URI", "http://host.docker.internal:19530")),
        "MILVUS_COLLECTION": vector_config.get("milvus_collection", "contextengine"),
        "MILVUS_DB_NAME": vector_config.get("milvus_db_name", "default"),
        "MILVUS_TIMEOUT": vector_config.get("milvus_timeout", os.environ.get("MILVUS_TIMEOUT", "30")),
        "MILVUS_TOKEN": os.environ.get("MILVUS_TOKEN", ""),
        "INSTANCE_NAME": instance_name,
        "OPENGAUSS_HOST_PORT": opengauss_port,
        "OGMEM_HTTP_HOST_PORT": ogmem_http_port,
        "OGMEM_MCP_HOST_PORT": ogmem_mcp_port,
        "OPENCLAW_CE_HOST_PORT": openclaw_ce_port,
        "OPENCLAW_MCP_HOST_PORT": openclaw_mcp_port,
        "LLM_BASE_URL": llm_config.get("base_url", ""),
        "LLM_MODEL": llm_config.get("model", ""),
        "LLM_API_KEY": llm_config.get("api_key", ""),
        "EMBEDDING_PROVIDER": QUICKSTART_EMBEDDING_PROVIDERS[embedding_provider],
        "EMBEDDING_BASE_URL": embedding_config.get("base_url", ""),
        "EMBEDDING_MODEL": embedding_config.get("model", ""),
        "EMBEDDING_API_KEY": embedding_config.get("api_key", ""),
        "EMBEDDING_DIMENSION": embedding_config.get("dimension", 1024),
    }
    lines = [
        "# Generated by ogmem onboard; consumed by deploy/user-quickstart/deploy.sh",
        *[f"export {name}={shlex.quote(str(value))}" for name, value in values.items()],
        "",
        "# Re-running Docker onboard recreates containers but preserves these directories.",
        "# Set RESET_* explicitly only when the corresponding data can be discarded.",
        "export RESET_OPENCLAW_CONFIG='false'",
        "export RESET_AGFS_DATA='false'",
        "export RESET_OPENGAUSS_DATA='false'",
    ]
    private_write(output_path, "\n".join(lines) + "\n")
    return output_path

def _quickstart_invocation(
    *,
    env_file: Path,
    stack_root: Path,
    runtime_env_file: Path,
) -> tuple[list[str], dict[str, str]]:
    """Share executable and state paths between immediate and deferred runs."""
    root = get_project_root()
    quickstart = root / "deploy" / "user-quickstart" / "deploy.sh"
    return ["bash", str(quickstart)], {
        "OGMEMORY_ENV_FILE": str(env_file),
        "OGMEMORY_STACK_ROOT": str(stack_root),
        "OGMEMORY_RUNTIME_ENV_FILE": str(runtime_env_file),
    }


def quickstart_shell_command(*, env_file: Path, stack_root: Path, runtime_env_file: Path) -> str:
    """Return a copyable POSIX command, including safely quoted state paths."""
    command, settings = _quickstart_invocation(
        env_file=env_file, stack_root=stack_root, runtime_env_file=runtime_env_file,
    )
    return shlex.join(["env", *[f"{key}={value}" for key, value in settings.items()], *command])


def deploy_quickstart(
    *,
    env_file: Path,
    stack_root: Path,
    runtime_env_file: Path,
) -> int:
    """Run the repository's user-quickstart Docker deployment unchanged."""
    command, settings = _quickstart_invocation(
        env_file=env_file, stack_root=stack_root, runtime_env_file=runtime_env_file,
    )
    if not Path(command[1]).exists():
        logger.error("user-quickstart deploy.sh not found at %s", command[1])
        return 1

    env = os.environ.copy()
    env.update(settings)
    logger.info("Running user-quickstart: %s", command[1])
    result = subprocess.run(command, cwd=str(get_project_root()), env=env)
    return result.returncode
