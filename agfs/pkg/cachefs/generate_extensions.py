"""Generate structural wrappers preserving the backend's optional method set."""
from pathlib import Path
facets = [('Toucher','touch'),('Truncater','truncate'),('RandomWriter','randomWrite'),('Syncer','syncFile'),('Streamer','stream'),('HandleFS','handles')]
s = ['// Code generated by generate_extensions.py; DO NOT EDIT.\npackage cachefs\n', 'import "github.com/c4pt0r/agfs/agfs-server/pkg/filesystem"\n', '// Wrap preserves optional extension interfaces without advertising unsupported operations.\nfunc Wrap(f *FS) filesystem.FileSystem {\nmask := 0\n']
for i,(interface, _) in enumerate(facets):
    s.append(f'if _,ok:=f.backend.(filesystem.{interface});ok{{mask|={1<<i}}}\n')
s.append('switch mask {\n')
for mask in range(1 << len(facets)):
    active=[n for i,(_,n) in enumerate(facets) if mask&(1<<i)]
    fields=';'.join(['*FS']+['*'+n for n in active])
    values=['f']+[('&handles{f:f,open:make(map[int64]*cachedHandle)}' if n=='handles' else f'&{n}{{f:f}}') for n in active]
    s.append(f'case {mask}: return &struct{{{fields}}}{{{",".join(values)}}}\n')
s.append('}\n panic("unreachable extension mask")\n}\n')
Path(__file__).with_name('extensions_generated.go').write_text(''.join(s))
